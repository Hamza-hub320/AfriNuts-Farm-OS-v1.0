package com.afrinuts.farmos.ui.suppliers;

import android.Manifest;
import android.app.Dialog;
import android.content.pm.PackageManager;
import android.location.Location;
import android.os.Bundle;
import android.text.TextUtils;
import android.view.LayoutInflater;
import android.view.View;
import android.widget.ArrayAdapter;
import android.widget.Button;
import android.widget.Toast;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;
import androidx.appcompat.app.AlertDialog;
import androidx.core.app.ActivityCompat;
import androidx.core.content.ContextCompat;
import androidx.fragment.app.DialogFragment;

import com.afrinuts.farmos.R;
import com.afrinuts.farmos.data.local.entity.SupplierEntity;
import com.afrinuts.farmos.data.repository.SupplierRepository;
import com.afrinuts.farmos.utils.RegistrationNumberGenerator;
import com.google.android.gms.location.FusedLocationProviderClient;
import com.google.android.gms.location.LocationServices;
import com.google.android.gms.tasks.OnSuccessListener;
import com.google.android.material.dialog.MaterialAlertDialogBuilder;
import com.google.android.material.textfield.MaterialAutoCompleteTextView;
import com.google.android.material.textfield.TextInputEditText;
import androidx.appcompat.widget.SwitchCompat;

import java.text.SimpleDateFormat;
import java.util.Locale;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;

public class AddSupplierDialog extends DialogFragment {

    private static final String ARG_FARM_ID = "farm_id";
    private static final int LOCATION_PERMISSION_REQUEST_CODE = 1001;

    private long farmId;
    private SupplierRepository repository;
    private final ExecutorService executor = Executors.newSingleThreadExecutor();
    private FusedLocationProviderClient fusedLocationClient;

    // UI Elements
    private TextInputEditText etName;
    private TextInputEditText etContactPerson;
    private TextInputEditText etPhone;
    private TextInputEditText etEmail;
    private TextInputEditText etLocation;
    private TextInputEditText etCountry;
    private TextInputEditText etLatitude;
    private TextInputEditText etLongitude;
    private MaterialAutoCompleteTextView etType;
    private TextInputEditText etRegistrationNumber;
    private TextInputEditText etAnnualVolume;
    private TextInputEditText etCertificationType;
    private TextInputEditText etCertificationNumber;
    private TextInputEditText etCertificationExpiry;
    private TextInputEditText etYearsFarming;
    private TextInputEditText etFarmSize;
    private TextInputEditText etQuote;
    private TextInputEditText etBio;
    private SwitchCompat switchFirebreak;
    private SwitchCompat switchSustainable;
    private SwitchCompat switchChildLabor;
    private TextInputEditText etNotes;
    private Button btnCancel;
    private Button btnSave;
    private Button btnGetLocation;
    private boolean isRegistrationAutoGenerated = true;

    public interface OnSupplierAddedListener {
        void onSupplierAdded();
    }

    private OnSupplierAddedListener listener;

    public static AddSupplierDialog newInstance(long farmId) {
        AddSupplierDialog dialog = new AddSupplierDialog();
        Bundle args = new Bundle();
        args.putLong(ARG_FARM_ID, farmId);
        dialog.setArguments(args);
        return dialog;
    }

    public void setOnSupplierAddedListener(OnSupplierAddedListener listener) {
        this.listener = listener;
    }

    @Override
    public void onCreate(@Nullable Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);

        if (getArguments() != null) {
            farmId = getArguments().getLong(ARG_FARM_ID);
        }

        repository = new SupplierRepository(requireContext(), farmId);
        fusedLocationClient = LocationServices.getFusedLocationProviderClient(requireContext());
    }

    @NonNull
    @Override
    public Dialog onCreateDialog(@Nullable Bundle savedInstanceState) {
        View view = LayoutInflater.from(getContext()).inflate(R.layout.dialog_add_supplier, null);

        initViews(view);
        setupTypeDropdown();
        setupLocationButton();
        setupAutoRegistrationNumber();

        MaterialAlertDialogBuilder builder = new MaterialAlertDialogBuilder(requireContext())
                .setView(view)
                .setCancelable(false);

        AlertDialog dialog = builder.create();

        dialog.setOnShowListener(dialogInterface -> {
            Button btnSave = dialog.getButton(AlertDialog.BUTTON_POSITIVE);
            Button btnCancel = dialog.getButton(AlertDialog.BUTTON_NEGATIVE);
            btnSave.setVisibility(View.GONE);
            btnCancel.setVisibility(View.GONE);
        });

        return dialog;
    }

    private void initViews(View view) {
        etName = view.findViewById(R.id.etName);
        etContactPerson = view.findViewById(R.id.etContactPerson);
        etPhone = view.findViewById(R.id.etPhone);
        etEmail = view.findViewById(R.id.etEmail);
        etLocation = view.findViewById(R.id.etLocation);
        etCountry = view.findViewById(R.id.etCountry);
        etLatitude = view.findViewById(R.id.etLatitude);
        etLongitude = view.findViewById(R.id.etLongitude);
        etType = view.findViewById(R.id.etType);
        etRegistrationNumber = view.findViewById(R.id.etRegistrationNumber);
        etAnnualVolume = view.findViewById(R.id.etAnnualVolume);
        etCertificationType = view.findViewById(R.id.etCertificationType);
        etCertificationNumber = view.findViewById(R.id.etCertificationNumber);
        etCertificationExpiry = view.findViewById(R.id.etCertificationExpiry);
        etYearsFarming = view.findViewById(R.id.etYearsFarming);
        etFarmSize = view.findViewById(R.id.etFarmSize);
        etQuote = view.findViewById(R.id.etQuote);
        etBio = view.findViewById(R.id.etBio);
        switchFirebreak = view.findViewById(R.id.switchFirebreak);
        switchSustainable = view.findViewById(R.id.switchSustainable);
        switchChildLabor = view.findViewById(R.id.switchChildLabor);
        etNotes = view.findViewById(R.id.etNotes);
        btnGetLocation = view.findViewById(R.id.btnGetLocation);

        btnCancel = view.findViewById(R.id.btnCancel);
        btnSave = view.findViewById(R.id.btnSave);

        btnCancel.setOnClickListener(v -> dismiss());
        btnSave.setOnClickListener(v -> saveSupplier());

        // Set default country
        etCountry.setText("Côte d'Ivoire");

        // Set GPS hints
        etLatitude.setHint("Latitude (e.g., 9.51)");
        etLongitude.setHint("Longitude (e.g., -7.57)");
    }

    private void setupTypeDropdown() {
        SupplierEntity.SupplierType[] types = SupplierEntity.SupplierType.values();
        String[] typeNames = new String[types.length];

        for (int i = 0; i < types.length; i++) {
            typeNames[i] = types[i].getDisplayName(); // Remove emoji icons
        }

        ArrayAdapter<String> adapter = new ArrayAdapter<>(
                requireContext(),
                android.R.layout.simple_dropdown_item_1line,
                typeNames
        );

        etType.setAdapter(adapter);
        etType.setText(typeNames[0], false);
    }

    private void setupLocationButton() {
        btnGetLocation.setOnClickListener(v -> {
            if (ContextCompat.checkSelfPermission(requireContext(),
                    Manifest.permission.ACCESS_FINE_LOCATION) != PackageManager.PERMISSION_GRANTED) {
                requestPermissions(
                        new String[]{Manifest.permission.ACCESS_FINE_LOCATION},
                        LOCATION_PERMISSION_REQUEST_CODE
                );
                return;
            }
            getCurrentLocation();
        });
    }

    private void setupAutoRegistrationNumber() {
        // Auto-generate registration number based on type
        etType.setOnItemClickListener((parent, view, position, id) -> {
            String typeStr = (String) parent.getItemAtPosition(position);
            SupplierEntity.SupplierType type = getTypeFromDisplay(typeStr);
            String regNumber = RegistrationNumberGenerator.generateRegistrationNumber(type);
            etRegistrationNumber.setText(regNumber);
            isRegistrationAutoGenerated = true;
        });

        // If user manually edits, we assume they want custom
        etRegistrationNumber.setOnFocusChangeListener((v, hasFocus) -> {
            if (hasFocus && isRegistrationAutoGenerated) {
                isRegistrationAutoGenerated = false;
                etRegistrationNumber.setHint("Enter custom or auto-generate");
            }
        });

        // Generate initial registration number
        generateInitialRegistrationNumber();
    }

    private void generateInitialRegistrationNumber() {
        String typeStr = etType.getText().toString().trim();
        if (!TextUtils.isEmpty(typeStr)) {
            SupplierEntity.SupplierType type = getTypeFromDisplay(typeStr);
            String regNumber = RegistrationNumberGenerator.generateRegistrationNumber(type);
            etRegistrationNumber.setText(regNumber);
        }
    }

    /**
     * Helper method to get SupplierType from display string
     */
    private SupplierEntity.SupplierType getTypeFromDisplay(String display) {
        for (SupplierEntity.SupplierType type : SupplierEntity.SupplierType.values()) {
            if (display.contains(type.getDisplayName())) {
                return type;
            }
        }
        return SupplierEntity.SupplierType.COOPERATIVE;
    }

    private void getCurrentLocation() {
        btnGetLocation.setEnabled(false);
        btnGetLocation.setText("Getting location...");

        if (ActivityCompat.checkSelfPermission(requireContext(),
                Manifest.permission.ACCESS_FINE_LOCATION) != PackageManager.PERMISSION_GRANTED) {
            btnGetLocation.setEnabled(true);
            btnGetLocation.setText("Get Current Location");
            return;
        }

        fusedLocationClient.getLastLocation()
                .addOnSuccessListener(requireActivity(), new OnSuccessListener<Location>() {
                    @Override
                    public void onSuccess(Location location) {
                        btnGetLocation.setEnabled(true);
                        btnGetLocation.setText("Get Current Location");

                        if (location != null) {
                            double lat = location.getLatitude();
                            double lng = location.getLongitude();

                            etLatitude.setText(String.format("%.6f", lat));
                            etLongitude.setText(String.format("%.6f", lng));

                            Toast.makeText(getContext(),
                                    "Location captured",
                                    Toast.LENGTH_LONG).show();

                            if (TextUtils.isEmpty(etLocation.getText())) {
                                etLocation.setText("GPS: " + String.format("%.6f", lat) + ", " + String.format("%.6f", lng));
                            }
                        } else {
                            Toast.makeText(getContext(),
                                    "Unable to get location. Try again or enter manually.",
                                    Toast.LENGTH_LONG).show();
                        }
                    }
                })
                .addOnFailureListener(e -> {
                    btnGetLocation.setEnabled(true);
                    btnGetLocation.setText("Get Current Location");
                    Toast.makeText(getContext(),
                            "Error getting location",
                            Toast.LENGTH_SHORT).show();
                });
    }

    @Override
    public void onRequestPermissionsResult(int requestCode, @NonNull String[] permissions,
                                           @NonNull int[] grantResults) {
        if (requestCode == LOCATION_PERMISSION_REQUEST_CODE) {
            if (grantResults.length > 0 && grantResults[0] == PackageManager.PERMISSION_GRANTED) {
                getCurrentLocation();
            } else {
                Toast.makeText(getContext(),
                        "Location permission denied. You can enter coordinates manually.",
                        Toast.LENGTH_LONG).show();
            }
        }
        super.onRequestPermissionsResult(requestCode, permissions, grantResults);
    }

    private void saveSupplier() {
        String name = etName.getText().toString().trim();
        if (TextUtils.isEmpty(name)) {
            etName.setError("Name is required");
            return;
        }

        String typeStr = etType.getText().toString().trim();
        SupplierEntity.SupplierType type = getTypeFromDisplay(typeStr);

        String contactPerson = etContactPerson.getText().toString().trim();
        String phone = etPhone.getText().toString().trim();
        String email = etEmail.getText().toString().trim();
        String location = etLocation.getText().toString().trim();
        String country = etCountry.getText().toString().trim();
        String registrationNumber = etRegistrationNumber.getText().toString().trim();

        // Parse GPS coordinates
        double latitude = 0;
        double longitude = 0;
        String latStr = etLatitude.getText().toString().trim();
        String lonStr = etLongitude.getText().toString().trim();
        boolean hasLocation = false;

        if (!TextUtils.isEmpty(latStr) && !TextUtils.isEmpty(lonStr)) {
            try {
                latitude = Double.parseDouble(latStr);
                longitude = Double.parseDouble(lonStr);
                hasLocation = true;

                if (latitude < -90 || latitude > 90) {
                    etLatitude.setError("Latitude must be between -90 and 90");
                    return;
                }
                if (longitude < -180 || longitude > 180) {
                    etLongitude.setError("Longitude must be between -180 and 180");
                    return;
                }
            } catch (NumberFormatException e) {
                Toast.makeText(getContext(), "Invalid GPS coordinates", Toast.LENGTH_SHORT).show();
                return;
            }
        }

        // Parse annual volume
        double annualVolume = 0;
        try {
            String volumeStr = etAnnualVolume.getText().toString().trim();
            if (!TextUtils.isEmpty(volumeStr)) {
                annualVolume = Double.parseDouble(volumeStr);
            }
        } catch (NumberFormatException e) {
            etAnnualVolume.setError("Invalid volume");
            return;
        }

        // Parse certification fields
        String certificationType = etCertificationType.getText().toString().trim();
        String certificationNumber = etCertificationNumber.getText().toString().trim();
        long certificationExpiryDate = 0;
        boolean isCertified = !TextUtils.isEmpty(certificationType);

        String expiryStr = etCertificationExpiry.getText().toString().trim();
        if (!TextUtils.isEmpty(expiryStr)) {
            try {
                SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd", Locale.getDefault());
                java.util.Date date = sdf.parse(expiryStr);
                if (date != null) {
                    certificationExpiryDate = date.getTime();
                }
            } catch (Exception e) {
                etCertificationExpiry.setError("Invalid date format. Use YYYY-MM-DD");
                return;
            }
        }

        // ✅ Create supplier FIRST
        SupplierEntity supplier = new SupplierEntity(
                farmId,
                name,
                type,
                contactPerson.isEmpty() ? null : contactPerson,
                phone.isEmpty() ? null : phone,
                location.isEmpty() ? null : location,
                registrationNumber
        );

        // ✅ Then set all the fields on the supplier
        supplier.setEmail(email.isEmpty() ? null : email);
        supplier.setCountry(country.isEmpty() ? null : country);
        supplier.setAnnualVolumeKg(annualVolume);
        supplier.setCertificationType(certificationType.isEmpty() ? null : certificationType);
        supplier.setCertificationNumber(certificationNumber.isEmpty() ? null : certificationNumber);
        supplier.setCertificationExpiryDate(certificationExpiryDate);
        supplier.setCertified(isCertified);
        supplier.setNotes(etNotes.getText().toString().trim());

        if (hasLocation) {
            supplier.setLatitude(latitude);
            supplier.setLongitude(longitude);
            supplier.setHasLocation(true);
        }

        // ✅ Set farmer profile fields
        // Parse years farming
        int yearsFarming = 0;
        String yearsStr = etYearsFarming.getText().toString().trim();
        if (!TextUtils.isEmpty(yearsStr)) {
            try {
                yearsFarming = Integer.parseInt(yearsStr);
            } catch (NumberFormatException e) {
                // Ignore, keep as 0
            }
        }

        // Parse farm size
        double farmSize = 0;
        String farmSizeStr = etFarmSize.getText().toString().trim();
        if (!TextUtils.isEmpty(farmSizeStr)) {
            try {
                farmSize = Double.parseDouble(farmSizeStr);
            } catch (NumberFormatException e) {
                // Ignore, keep as 0
            }
        }

        // Get quote and bio
        String quote = etQuote.getText().toString().trim();
        String bio = etBio.getText().toString().trim();

        // Get switches
        boolean firebreakProtection = switchFirebreak.isChecked();
        boolean sustainableHarvesting = switchSustainable.isChecked();
        boolean noChildLabor = switchChildLabor.isChecked();

        // Set farmer profile fields on supplier
        supplier.setYearsFarming(yearsFarming);
        supplier.setFarmSize(farmSize);
        supplier.setQuote(quote);
        supplier.setBio(bio);
        supplier.setFirebreakProtection(firebreakProtection);
        supplier.setSustainableHarvesting(sustainableHarvesting);
        supplier.setNoChildLabor(noChildLabor);

        btnSave.setEnabled(false);
        btnSave.setText("Saving...");

        repository.insertSupplier(supplier, new SupplierRepository.InsertCallback() {
            @Override
            public void onSuccess(long id) {
                if (getActivity() != null) {
                    getActivity().runOnUiThread(() -> {
                        Toast.makeText(getContext(), "Supplier added!", Toast.LENGTH_SHORT).show();
                        if (listener != null) {
                            listener.onSupplierAdded();
                        }
                        dismiss();
                    });
                }
            }

            @Override
            public void onError(String error) {
                if (getActivity() != null) {
                    getActivity().runOnUiThread(() -> {
                        btnSave.setEnabled(true);
                        btnSave.setText("Add Supplier");
                        Toast.makeText(getContext(), "Error: " + error, Toast.LENGTH_LONG).show();
                    });
                }
            }
        });
    }

    @Override
    public void onDestroy() {
        super.onDestroy();
        if (repository != null) {
            repository.shutdown();
        }
        executor.shutdown();
    }
}